// solve.js — a faster drop-in for makefun-site 1.0.0.
//
// Same answer as makefun-site 1.0.0's build() for every input, byte for byte,
// written as one dependency-free ES module. It re-implements the reference
// pipeline (front matter, Markdown subset, template dialect, slug rule,
// report) with the same rules and the same output, but faster: bulk HTML
// escaping instead of one regex per character, a single-pass Markdown
// scanner instead of per-line regexes, an ASCII fast path for slugs with a
// per-build memo, and a template renderer that writes into one array over a
// single flat scope instead of allocating a scope object per loop item.
//
// Nothing is cached from one case to the next: every run(input) parses its
// templates, builds its own slug memo and renders from fresh state.

/** Code-unit order (never the locale's). */
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The top-level directories the generator writes itself, which no page's slug at the root may take. */
const RESERVED = ['posts', 'tags', 'page'];

const dirOf = (path) => (path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '');

// ---------------------------------------------------------------- text

/** The HTML escape table, in this order: & < > " ' */
const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/g;

const ESC_TEST = /[&<>"']/;
/** `text` with & < > " and ' escaped. */
function escapeHtml(text) {
  if (!ESC_TEST.test(text)) return text;
  return text.replace(ESC_RE, (c) => ESCAPES[c]);
}

/** The most characters a slug keeps before a collision suffix. */
const SLUG_MAX = 64;
const NON_ASCII = /[^\x00-\x7F]/;
const MARKS = /\p{M}/gu;

/** The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of characters other than a-z and 0-9 one
 * "-", none at either end, at most SLUG_MAX characters (a "-" left at the cut dropped), and "untitled" when nothing is
 * left. ASCII text takes a fast path: NFKD is the identity on ASCII and ASCII holds no combining marks. */
function slugifyRaw(text) {
  if (!NON_ASCII.test(text)) {
    let out = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
    out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
    return out === '' ? 'untitled' : out;
  }
  const plain = text.normalize('NFKD').replace(MARKS, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it): the first of slug, slug-2, slug-3 ... not taken. */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone: "2026-11-09" is "9 November 2026". */
function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

/** The words of a body: its runs of characters other than whitespace. */
const WS_RE = /\s/;
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    const ws = code === 32 || (code >= 9 && code <= 13) || (code >= 128 && WS_RE.test(text[i]));
    if (ws) inWord = false;
    else if (!inWord) {
      inWord = true;
      n++;
    }
  }
  return n;
}

// ---------------------------------------------------------------- front matter

/** The keys a source's front matter may give. */
const FM_KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];

/** The days of month `m` (1-12) of year `y`, by the Gregorian rule. */
function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return [4, 6, 9, 11].includes(m) ? 30 : 31;
}

function isLowerAlnum(c) {
  return (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9');
}

/** A string value: "..." with \" and \\ its only escapes, or bare, the rest of the line (never opening on " or [). */
function fmString(raw) {
  if (raw.charCodeAt(0) === 34) {
    if (raw.length < 2 || raw.charCodeAt(raw.length - 1) !== 34) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function fmValue(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = fmString(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      let y = 0;
      let mo = 0;
      let d = 0;
      if (ok) {
        for (let i = 0; i < 4; i++) {
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) ok = false;
          else y = y * 10 + (c - 48);
        }
        for (let i = 5; i < 7; i++) {
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) ok = false;
          else mo = mo * 10 + (c - 48);
        }
        for (let i = 8; i < 10; i++) {
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) ok = false;
          else d = d * 10 + (c - 48);
        }
      }
      if (!ok || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) {
        return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      }
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if (!isLowerAlnum(c) && c !== '-') return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      if (raw.length === 0 || raw.length > 64 || !isLowerAlnum(raw[0])) return { error: 'key "slug": not a slug' };
      let i = 0;
      while (i < raw.length) {
        if (!isLowerAlnum(raw[i])) return { error: 'key "slug": not a slug' };
        i++;
        while (i < raw.length && isLowerAlnum(raw[i])) i++;
        if (i < raw.length) {
          if (raw[i] !== '-' || i + 1 >= raw.length || !isLowerAlnum(raw[i + 1])) return { error: 'key "slug": not a slug' };
          i++;
        }
      }
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/** Whether `line` is blank (spaces and tabs only). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) if (line[i] !== ' ' && line[i] !== '\t') return false;
  return true;
}

/**
 * A source's front matter and body: { data, body }, or { error } with the first reason it is refused. `text` has "\n"
 * line ends.
 */
function parseFrontMatter(text) {
  const firstNl = text.indexOf('\n');
  const firstEnd = firstNl === -1 ? text.length : firstNl;
  if (text.slice(0, firstEnd) !== '---') return { error: 'no front matter' };
  let close = -1;
  let closeEnd = -1;
  let scan = firstNl === -1 ? text.length : firstNl + 1;
  while (scan <= text.length) {
    const e = text.indexOf('\n', scan);
    const end = e === -1 ? text.length : e;
    if (text.slice(scan, end) === '---') {
      close = scan;
      closeEnd = end;
      break;
    }
    if (e === -1) break;
    scan = e + 1;
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  let p = firstNl === -1 ? text.length : firstNl + 1;
  let idx = 1;
  while (p < close) {
    const e = text.indexOf('\n', p);
    const end = e === -1 ? text.length : e;
    const line = text.slice(p, end);
    if (!isBlank(line) && line[0] !== '#') {
      let k = 0;
      while (k < line.length && ((line[k] >= 'a' && line[k] <= 'z') || line[k] === '_')) k++;
      if (k === 0 || line[k] !== ':') return { error: `line ${idx + 1} is not "key: value"` };
      const key = line.slice(0, k);
      let raw;
      if (k + 1 === line.length) raw = '';
      else if (line[k + 1] === ' ') raw = line.slice(k + 2);
      else return { error: `line ${idx + 1} is not "key: value"` };
      let rEnd = raw.length;
      while (rEnd > 0 && (raw[rEnd - 1] === ' ' || raw[rEnd - 1] === '\t')) rEnd--;
      raw = raw.slice(0, rEnd);
      if (!FM_KEYS.includes(key)) return { error: `unknown key "${key}"` };
      if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
      if (raw === '') return { error: `key "${key}" has no value` };
      const v = fmValue(key, raw);
      if ('error' in v) return v;
      data[key] = v.value;
    }
    p = end + 1;
    idx++;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  const body = closeEnd === text.length ? '' : text.slice(closeEnd + 1);
  return { data, body };
}

// ---------------------------------------------------------------- markdown

/** A paragraph line as it is rendered: spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

/** A fence's language, or null when `line` does not open one. */
function fenceOpen(line) {
  if (!line.startsWith('```')) return null;
  let k = 3;
  while (k < line.length) {
    const c = line.charCodeAt(k);
    if (!((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45)) break;
    k++;
  }
  for (let j = k; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return null;
  return line.slice(3, k);
}

/** Whether `line` closes a fence. */
function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let k = 0;
  while (k < line.length && line[k] === '#') k++;
  if (k === 0 || k > 6) return null;
  if (k >= line.length || (line[k] !== ' ' && line[k] !== '\t')) return null;
  let j = k;
  while (j < line.length && (line[j] === ' ' || line[j] === '\t')) j++;
  let end = line.length;
  while (end > j && (line[end - 1] === ' ' || line[end - 1] === '\t')) end--;
  if (end === j) return null;
  return { depth: k, text: line.slice(j, end) };
}

/** Whether `line` is a thematic break. */
function isHr(line) {
  const p = line.slice(0, 3);
  if (p !== '---' && p !== '***') return false;
  for (let j = 3; j < line.length; j++) if (line[j] !== ' ' && line[j] !== '\t') return false;
  return true;
}

/** A bullet item's text, or null when `line` does not start one. */
function bulletOf(line) {
  if (line.length < 2) return null;
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's start number and text, or null when `line` does not start one. */
function orderedOf(line) {
  let k = 0;
  while (k < line.length && line.charCodeAt(k) >= 48 && line.charCodeAt(k) <= 57) k++;
  if (k === 0 || k > 9) return null;
  if (line[k] !== '.' || line[k + 1] !== ' ') return null;
  return { start: Number(line.slice(0, k)), text: line.slice(k + 2) };
}

/** Whether `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  let k = 0;
  while (k < line.length && line[k] === ' ') k++;
  if (k < 2 || k >= line.length) return false;
  const c = line.charCodeAt(k);
  if (c === 32 || (c >= 9 && c <= 13)) return false;
  if (c >= 128) return !WS_RE.test(line[k]);
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

// Block classes, one scan per line instead of a regex per question:
// 0 blank, 1 fence, 2 heading, 3 thematic break, 4 blockquote, 5 bullet, 6 ordered, 7 paragraph, 8 list continuation.
function classify(line) {
  const n = line.length;
  if (n === 0) return 0;
  const c0 = line.charCodeAt(0);
  if (c0 === 32 || c0 === 9) {
    let s = 0;
    while (s < n && line[s] === ' ') s++;
    let k = s;
    let blank = true;
    while (k < n) {
      if (line[k] !== ' ' && line[k] !== '\t') {
        blank = false;
        break;
      }
      k++;
    }
    if (blank) return 0;
    if (s >= 2) {
      const c = line.charCodeAt(s);
      if (c !== 32 && !(c >= 9 && c <= 13) && (c < 128 || !WS_RE.test(line[s]))) return 8;
    }
    return 7;
  }
  if (c0 === 96) return fenceOpen(line) !== null ? 1 : 7;
  if (c0 === 35) return headingOf(line) !== null ? 2 : 7;
  if (c0 === 45) {
    if (isHr(line)) return 3;
    if (n >= 2 && line.charCodeAt(1) === 32) return 5;
    return 7;
  }
  if (c0 === 42) {
    if (isHr(line)) return 3;
    if (n >= 2 && line.charCodeAt(1) === 32) return 5;
    return 7;
  }
  if (c0 === 62) return 4;
  if (c0 >= 48 && c0 <= 57) return orderedOf(line) !== null ? 6 : 7;
  return 7;
}

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  let j = s.indexOf(what, from);
  while (j !== -1) {
    let k = j - 1;
    let bs = 0;
    while (k >= from && s[k] === '\\') {
      bs++;
      k--;
    }
    if (bs % 2 === 0) return j;
    j = s.indexOf(what, j + 1);
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  let j = s.indexOf('*', from);
  while (j !== -1) {
    let k = j - 1;
    let bs = 0;
    while (k >= from && s[k] === '\\') {
      bs++;
      k--;
    }
    if (bs % 2 === 1) {
      j = s.indexOf('*', j + 1);
      continue;
    }
    if (s[j + 1] === '*') {
      j = s.indexOf('*', j + 2);
      continue;
    }
    return j;
  }
  return -1;
}

/** `s` rendered inline; `env.link(target)` is a link's href. */
function inline(s, env) {
  const parts = [];
  const n = s.length;
  let i = 0;
  let run = 0;
  while (i < n) {
    const c = s[i];
    if (c === '\\' && i + 1 < n && ESCAPABLE.has(s[i + 1])) {
      if (i > run) parts.push(escapeHtml(s.slice(run, i)));
      parts.push(escapeHtml(s[i + 1]));
      i += 2;
      run = i;
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > run) parts.push(escapeHtml(s.slice(run, i)));
        parts.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        run = i;
      } else {
        i++;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > run) parts.push(escapeHtml(s.slice(run, i)));
          parts.push('<strong>', inline(s.slice(i + 2, j), env), '</strong>');
          i = j + 2;
          run = i;
        } else {
          i += 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > run) parts.push(escapeHtml(s.slice(run, i)));
        parts.push('<em>', inline(s.slice(i + 1, j), env), '</em>');
        i = j + 1;
        run = i;
      } else {
        i++;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !WS_RE.test(target)) {
        if (i > run) parts.push(escapeHtml(s.slice(run, i)));
        parts.push('<a href="', escapeHtml(env.link(target)), '">', inline(s.slice(i + 1, k), env), '</a>');
        i = m + 1;
        run = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  if (n > run) parts.push(escapeHtml(s.slice(run, n)));
  return parts.join('');
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of contents (every level 2
 * and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 */
function renderMarkdown(src, env, slugify) {
  const lines = src.split('\n');
  const L = lines.length;
  const cls = new Uint8Array(L);
  for (let k = 0; k < L; k++) cls[k] = classify(lines[k]);
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < L) {
    const line = lines[i];
    const cl = cls[i];
    if (cl === 0) {
      i++;
      continue;
    }
    if (cl === 1) {
      const fenceLang = fenceOpen(line);
      const body = [];
      i++;
      while (i < L && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      parts.push('<pre><code');
      if (fenceLang !== '') parts.push(` class="language-${escapeHtml(fenceLang)}"`);
      parts.push('>');
      for (let b = 0; b < body.length; b++) {
        parts.push(escapeHtml(body[b]));
        parts.push('\n');
      }
      parts.push('</code></pre>\n');
      continue;
    }
    if (cl === 2) {
      const heading = headingOf(line);
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      parts.push(`<h${heading.depth} id="${id}">`, html, `</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (cl === 3) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (cl === 4) {
      const body = [];
      while (i < L && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.startsWith('> ') ? l.slice(2) : l.slice(1));
      }
      const inner = [];
      for (let b = 0; b < body.length; b++) {
        const t = trimLine(body[b]);
        if (t !== '') inner.push(t);
      }
      parts.push(inner.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(inner.join('\n'), env)}</p>\n</blockquote>\n`);
      continue;
    }
    if (cl === 5 || cl === 6) {
      const isOrdered = cl === 6;
      const items = [];
      const start = isOrdered ? orderedOf(line).start : 1;
      while (i < L) {
        if (isOrdered) {
          if (cls[i] === 6) {
            items.push([trimLine(orderedOf(lines[i]).text)]);
            i++;
            continue;
          }
        } else if (cls[i] === 5) {
          items.push([trimLine(bulletOf(lines[i]))]);
          i++;
          continue;
        }
        if (cls[i] === 8) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
          continue;
        }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      parts.push(isOrdered && start !== 1 ? `<ol start="${start}">\n` : `<${tag}>\n`);
      for (let k = 0; k < items.length; k++) {
        parts.push('<li>', inline(items[k].join('\n'), env), '</li>\n');
      }
      parts.push(`</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < L && cls[i] >= 4) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    parts.push('<p>', html, '</p>\n');
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

